"""Generate an IO_CONSTRAINTS Tcl file for a pin-placement strategy.

ORFS sources IO_CONSTRAINTS at the end of floorplan.tcl; the constraints are
stored in the odb and honoured by place_pins at 3_2_place_iop.

Strategies:
  default            no file: ORFS/place_pins decides freely
  bus_sides          each bus (and the scalar inputs/outputs) is one ordered
                     group, groups are spread over the four sides balancing
                     pin count, widest bus first
  in_left_out_right  every input on the left edge, every output on the right
                     (inouts at the bottom), each bus kept as an ordered group
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

_BUS_RE = re.compile(r"^(?P<base>.+?)\[(?P<index>\d+)\]$")
SIDES = ("left", "right", "bottom", "top")


@dataclass(frozen=True)
class Port:
    name: str
    direction: str  # INPUT / OUTPUT / INOUT
    sig_type: str = "SIGNAL"  # SIGNAL / CLOCK / POWER / GROUND


def bus_of(name: str) -> str:
    match = _BUS_RE.match(name)
    return match.group("base") if match else name


def bus_index(name: str) -> int:
    match = _BUS_RE.match(name)
    return int(match.group("index")) if match else 0


def signal_ports(ports: list[Port]) -> list[Port]:
    """Power/ground pins are not placed by place_pins; leave them out."""
    return [p for p in ports if p.sig_type.upper() not in ("POWER", "GROUND")]


def groups_by_bus(ports: list[Port]) -> dict[str, list[Port]]:
    """Bus name -> its pins, LSB first. Scalars are grouped per direction so a
    design with 40 one-bit control inputs does not get 40 tiny groups."""
    groups: dict[str, list[Port]] = {}
    for port in signal_ports(ports):
        base = bus_of(port.name)
        if base == port.name:
            base = f"scalar_{port.direction.lower()}"
        groups.setdefault(base, []).append(port)
    for members in groups.values():
        members.sort(key=lambda p: (bus_index(p.name), p.name))
    return groups


def pin_groups(ports: list[Port], strategy: str) -> dict[str, str]:
    """pin name -> group label, used to color pins in the rendered floorplan.
    Every strategy (including default) groups by bus so the pictures compare."""
    return {
        port.name: group for group, members in groups_by_bus(ports).items() for port in members
    }


def _tcl_names(members: list[Port]) -> str:
    # Braces make brackets literal, so `data_o[3]` needs no escaping.
    return "{" + " ".join(p.name for p in members) + "}"


def assign_sides(ports: list[Port], strategy: str, aspect: float = 1.0) -> dict[str, str]:
    """group -> side for a strategy (empty for default).

    aspect is the die's height/width. bus_sides balances pins per unit of
    edge LENGTH, so on an AR 0.5 die the long top/bottom edges take twice the
    pins of the short left/right ones. At aspect 1 this is plain count
    balancing."""
    groups = groups_by_bus(ports)
    if strategy == "default":
        return {}
    if strategy == "in_left_out_right":
        sides = {}
        for name, members in groups.items():
            direction = members[0].direction.upper()
            sides[name] = {"INPUT": "left", "OUTPUT": "right"}.get(direction, "bottom")
        return sides
    if strategy == "bus_sides":
        load = {side: 0 for side in SIDES}
        length = {"left": aspect, "right": aspect, "bottom": 1.0, "top": 1.0}
        sides = {}
        # Widest first, then by name so the result is deterministic.
        for name, members in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            # Density AFTER adding this bus; ties go to the longer edge. With
            # equal lengths this is exactly "least-loaded side first".
            side = min(SIDES, key=lambda s: ((load[s] + len(members)) / length[s],
                                             -length[s], SIDES.index(s)))
            sides[name] = side
            load[side] += len(members)
        return sides
    raise ValueError(f"unknown io strategy {strategy!r}")


def generate(ports: list[Port], strategy: str, design: str = "", aspect: float = 1.0) -> Optional[str]:
    """Tcl text for the strategy, or None for default (no IO_CONSTRAINTS)."""
    if strategy == "default":
        return None
    groups = groups_by_bus(ports)
    if not groups:
        raise ValueError("no signal ports to constrain")
    sides = assign_sides(ports, strategy, aspect)

    lines = [
        f"# IO_CONSTRAINTS generated by adaptive_iicpilot FloorplanAgent",
        f"# design={design} strategy={strategy} pins={sum(len(m) for m in groups.values())} "
        f"groups={len(groups)}",
        f'puts "\\[Floorplan\\] IO_CONSTRAINTS strategy={strategy} groups={len(groups)}"',
    ]
    for name in sorted(groups, key=lambda g: (SIDES.index(sides[g]), g)):
        members = groups[name]
        side = sides[name]
        lines.append(f"# group {name}: {len(members)} pin(s) -> {side}")
        if len(members) > 1:
            lines.append(
                f"set_io_pin_constraint -region {side}:* -group -order -pin_names {_tcl_names(members)}"
            )
        else:
            lines.append(f"set_io_pin_constraint -region {side}:* -pin_names {_tcl_names(members)}")
    return "\n".join(lines) + "\n"


def side_summary(ports: list[Port], strategy: str, aspect: float = 1.0) -> dict[str, int]:
    """side -> pin count, for logging what a strategy asks for."""
    groups = groups_by_bus(ports)
    sides = assign_sides(ports, strategy, aspect)
    summary = {side: 0 for side in SIDES}
    for name, side in sides.items():
        summary[side] += len(groups[name])
    return summary
